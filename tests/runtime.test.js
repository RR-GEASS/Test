import test from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, cpSync, mkdirSync, readFileSync, readdirSync, symlinkSync, rmSync, existsSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { tmpdir } from "node:os";
import { spawnSync } from "node:child_process";
import { scryptSync } from "node:crypto";
import { DatabaseSync } from "node:sqlite";
import { createBackup, pruneBackups } from "../scripts/backup-lib.mjs";

const root=resolve(import.meta.dirname,'..');
test("les fichiers effectivement copiés dans le runtime Docker permettent de démarrer le serveur de production",()=>{
  const docker=readFileSync(join(root,'Dockerfile'),'utf8');
  assert.match(docker,/COPY[^\n]+src\/\*\.js \.\/src\//);
  assert.match(docker,/COPY[^\n]+scripts\/\*\.mjs \.\/scripts\//);
  const folder=mkdtempSync(join(tmpdir(),'capsci-runtime-'));
  try {
    cpSync(join(root,'server'),join(folder,'server'),{recursive:true});
    mkdirSync(join(folder,'src'));
    for(const name of readdirSync(join(root,'src')).filter(name=>name.endsWith('.js')))cpSync(join(root,'src',name),join(folder,'src',name));
    cpSync(join(root,'package.json'),join(folder,'package.json'));
    symlinkSync(join(root,'node_modules'),join(folder,'node_modules'),'dir');
    const code=`import {createApp} from './server/app.js';const {app,close}=createApp({dbPath:':memory:',production:true});const s=app.listen(0,'127.0.0.1',async()=>{try{const r=await fetch('http://127.0.0.1:'+s.address().port+'/api/health');if(!r.ok)throw Error('health');console.log('production-health-ok');}finally{s.close(()=>close());}});`;
    const result=spawnSync(process.execPath,['--input-type=module','-e',code],{cwd:folder,encoding:'utf8',timeout:10000});
    assert.equal(result.status,0,result.stderr);assert.match(result.stdout,/production-health-ok/);
  } finally {rmSync(folder,{recursive:true,force:true});}
});

test("la sauvegarde complète et la restauration conservent les comptes et les octets des documents sans écraser une base",async()=>{
  const folder=mkdtempSync(join(tmpdir(),'capsci-backup-'));
  const source=join(folder,'source.sqlite'),directory=join(folder,'backups');
  const db=new DatabaseSync(source);
  db.exec(`CREATE TABLE users(id TEXT,state TEXT);CREATE TABLE sessions(id TEXT);CREATE TABLE attachments(id TEXT,data BLOB);CREATE TABLE entity_documents(id TEXT,data BLOB);INSERT INTO users VALUES('owner','{}');`);
  const bytes=Buffer.from('%PDF-1.7\noriginal\n%%EOF');
  db.prepare("INSERT INTO attachments VALUES('a',?)").run(bytes);db.prepare("INSERT INTO entity_documents VALUES('d',?)").run(bytes);
  try {
    const backup=await createBackup({source,directory});
    const target=join(folder,'restored','atelier.sqlite');
    const result=spawnSync(process.execPath,[join(root,'scripts/restore.mjs'),backup,target],{encoding:'utf8',timeout:10000});
    assert.equal(result.status,0,result.stderr);
    const restored=new DatabaseSync(target,{readOnly:true});
    assert.equal(restored.prepare('SELECT count(*) AS n FROM users').get().n,1);
    assert.deepEqual(Buffer.from(restored.prepare('SELECT data FROM attachments').get().data),bytes);
    assert.deepEqual(Buffer.from(restored.prepare('SELECT data FROM entity_documents').get().data),bytes);restored.close();
    assert.equal(spawnSync(process.execPath,[join(root,'scripts/restore.mjs'),backup,target],{encoding:'utf8'}).status,1);
    assert.equal(existsSync(target),true);
    // Only filenames generated by our scheduler are candidates for rotation.
    writeFileSync(join(directory,'important.sqlite'),'keep');
    cpSync(backup,join(directory,'cap-sci-2000-01-01T00-00-00.000Z.sqlite'));
    pruneBackups(directory,1);
    assert.equal(existsSync(join(directory,'important.sqlite')),true);
    assert.equal(existsSync(backup),true);
  } finally {db.close();rmSync(folder,{recursive:true,force:true});}
});


test("la récupération administrateur change le mot de passe sans l’afficher et ferme les anciennes sessions",()=>{
  const folder=mkdtempSync(join(tmpdir(),'capsci-password-'));
  const db=new DatabaseSync(join(folder,'atelier.sqlite'));
  db.exec("CREATE TABLE users(id TEXT,email TEXT,password_hash TEXT,salt TEXT);CREATE TABLE sessions(token_hash TEXT,user_id TEXT,expires_at INTEGER);INSERT INTO users VALUES('u','owner@example.test','old','salt');INSERT INTO sessions VALUES('session','u',9999999999999);");
  const password='new-private-password-2026';
  try {
    const result=spawnSync(process.execPath,[join(root,'scripts/reset-password.mjs'),'owner@example.test'],{env:{...process.env,SCI_DATA_DIR:folder},input:password+'\n',encoding:'utf8',timeout:10000});
    assert.equal(result.status,0,result.stderr);
    assert.equal(result.stdout.includes(password),false);
    assert.equal(result.stderr.includes(password),false);
    const user=db.prepare("SELECT * FROM users WHERE id='u'").get();
    assert.equal(scryptSync(password,user.salt,64).toString('hex'),user.password_hash);
    assert.equal(db.prepare('SELECT count(*) AS n FROM sessions').get().n,0);
    const invalid=spawnSync(process.execPath,[join(root,'scripts/reset-password.mjs'),'owner@example.test'],{env:{...process.env,SCI_DATA_DIR:folder},input:'court',encoding:'utf8'});
    assert.equal(invalid.status,1);
    assert.equal(db.prepare("SELECT password_hash FROM users WHERE id='u'").get().password_hash,user.password_hash);
  } finally {db.close();rmSync(folder,{recursive:true,force:true});}
});
